import { mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import webpush from 'web-push';
import type { Check } from './store';

interface Keys {
  p256dh: string;
  auth: string;
}

interface Sub {
  endpoint: string;
  keys: Keys;
  checks: string[];
  admin: boolean;
  createdAt: string;
}

const FILE = join(resolve(process.env.DATA_DIR ?? 'data'), 'subs.json');

const PUBLIC = process.env.VAPID_PUBLIC_KEY ?? '';
const PRIVATE = process.env.VAPID_PRIVATE_KEY ?? '';
const SUBJECT = process.env.VAPID_SUBJECT ?? 'mailto:hello@juicey.dev';

const TTL = 60 * 60 * 24;
const MAX_SUBS = 2000;
const MAX_PER_CHECK = 50;
const EXPIRE = 90 * 24 * 60 * 60 * 1000;

const LABELS: Record<string, string> = {
  vibecoded: 'Vibecoded',
  diffusion: 'Diffusion Generated',
  claude: 'Generated by Claude',
  unsure: 'Unsure',
  possibly: 'Possibly not AI',
  notai: 'Not AI!',
};

export const pushReady = Boolean(PUBLIC && PRIVATE);

if (pushReady) webpush.setVapidDetails(SUBJECT, PUBLIC, PRIVATE);

const read = (): Sub[] => {
  try {
    const parsed = JSON.parse(readFileSync(FILE, 'utf8')) as { subs?: Sub[] };
    if (!Array.isArray(parsed.subs)) return [];
    return parsed.subs.filter(
      (sub) =>
        typeof sub?.endpoint === 'string' &&
        typeof sub?.keys?.p256dh === 'string' &&
        typeof sub?.keys?.auth === 'string' &&
        Array.isArray(sub?.checks),
    );
  } catch {
    return [];
  }
};

const write = (subs: Sub[]) => {
  mkdirSync(dirname(FILE), { recursive: true });
  const tmp = `${FILE}.tmp`;
  writeFileSync(tmp, JSON.stringify({ version: 1, subs }, null, 2), 'utf8');
  renameSync(tmp, FILE);
};

const current = (sub: Sub): boolean => {
  const at = Date.parse(sub.createdAt);
  return Number.isFinite(at) && Date.now() - at < EXPIRE;
};

export const subscribe = (
  endpoint: string,
  keys: Keys,
  checkId = '',
  admin = false,
): boolean => {
  if (!pushReady) return false;

  const subs = read().filter(current);
  const existing = subs.find((sub) => sub.endpoint === endpoint);

  if (existing) {
    if (checkId && !existing.checks.includes(checkId)) {
      if (existing.checks.length >= MAX_PER_CHECK) return false;
      existing.checks.push(checkId);
    }
    if (admin) existing.admin = true;
  } else {
    if (subs.length >= MAX_SUBS) return false;
    subs.push({
      endpoint,
      keys,
      checks: checkId ? [checkId] : [],
      admin,
      createdAt: new Date().toISOString(),
    });
  }

  write(subs);
  return true;
};

const alive = async (sub: Sub, payload: object): Promise<boolean> => {
  try {
    await webpush.sendNotification(
      { endpoint: sub.endpoint, keys: sub.keys },
      JSON.stringify(payload),
      { TTL },
    );
    return true;
  } catch (error) {
    const status = (error as { statusCode?: number }).statusCode;
    return status !== 404 && status !== 410;
  }
};

const host = (url: string): string => {
  try {
    return new URL(url).hostname.replace(/^www\./, '');
  } catch {
    return url;
  }
};

export const notifyCheck = async (check: Check): Promise<void> => {
  if (!pushReady) return;

  const subs = read().filter(current);
  const targets = subs.filter((sub) => sub.checks.includes(check.id));
  if (targets.length === 0) return;

  const payload = {
    title: 'is this ai?',
    body: `${LABELS[check.verdict] ?? 'Checked'}: ${check.title || host(check.url)}`,
    url: '/',
    tag: `check-${check.id}`,
  };

  const gone = new Set<string>();
  await Promise.all(
    targets.map(async (sub) => {
      if (await alive(sub, payload)) {
        sub.checks = sub.checks.filter((id) => id !== check.id);
      } else {
        gone.add(sub.endpoint);
      }
    }),
  );

  write(subs.filter((sub) => !gone.has(sub.endpoint) && (sub.checks.length > 0 || sub.admin)));
};

export const notifyAdmins = async (check: Check): Promise<void> => {
  if (!pushReady) return;

  const subs = read().filter(current);
  const targets = subs.filter((sub) => sub.admin);
  if (targets.length === 0) return;

  const payload = {
    title: 'new link to check',
    body: check.title || host(check.url),
    url: '/admin',
    tag: 'isthisai-admin',
  };

  const gone = new Set<string>();
  await Promise.all(
    targets.map(async (sub) => {
      if (!(await alive(sub, payload))) gone.add(sub.endpoint);
    }),
  );

  if (gone.size > 0) write(subs.filter((sub) => !gone.has(sub.endpoint)));
};
